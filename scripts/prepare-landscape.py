"""Fetch only public physical tree/bench attributes. Never fetch donors or editor data.

This is an explicit offline preparation command; the running app has no GIS dependency.
The original campus geometry/hash and all previous data files remain unchanged.
"""
from pathlib import Path
import urllib.request, urllib.parse, json, hashlib, datetime

ROOT = Path(__file__).resolve().parents[1]
BASE = 'https://gis.maps.uw.edu/federated/rest/services/PublicData/PublicData/'
CAMPUS = json.loads((ROOT/'data/campus.json').read_text(encoding='utf-8'))
SOURCES = ROOT/'sources'

def acquire(layer, fields, name):
    features, offset, urls = [], 0, []
    while True:
        query = dict(where='1=1', geometry='-122.3122,47.6524,-122.3034,47.6594',
            geometryType='esriGeometryEnvelope', inSR=4326, spatialRel='esriSpatialRelIntersects',
            outFields=fields, outSR=26910, f='json', returnGeometry='true',
            orderByFields='OBJECTID ASC', resultOffset=offset, resultRecordCount=2000)
        url = BASE+layer+'/query?'+urllib.parse.urlencode(query)
        data = json.load(urllib.request.urlopen(url, timeout=60))
        if 'error' in data: raise RuntimeError(data['error'])
        rows = data.get('features', [])
        features.extend(rows); urls.append(url)
        if not data.get('exceededTransferLimit'): break
        if not rows: raise RuntimeError('Pagination made no progress')
        offset += len(rows)
    raw = dict(format='uw.public-landscape-snapshot/v1', layer=layer,
        spatialReference={'wkid':26910}, fields=fields.split(','), features=features)
    path = SOURCES/name
    path.write_text(json.dumps(raw, ensure_ascii=False, separators=(',',':'))+'\n', encoding='utf-8')
    return features, dict(layer=BASE+layer, queryUrls=urls, file='sources/'+name,
        sha256=hashlib.sha256(path.read_bytes()).hexdigest(), features=len(features))

def main():
    tree_rows, tree_source = acquire('MapServer/37',
        'OBJECTID,TreeNumber,SpeciesName,CommonName,TreeType,Height,MeasurementDate', 'public-trees-090.json')
    bench_rows, bench_source = acquire('FeatureServer/6',
        'OBJECTID,FeatureStatus,Material', 'public-benches-090.json')
    e, n = CAMPUS['originEastingNorthing']
    def point(row):
        p=row['geometry']; return [round(p['x']-e,3),round(n-p['y'],3)]
    trees=[]
    for row in tree_rows:
        a=row['attributes']; p=point(row)
        trees.append(dict(id='uw-tree-'+str(a['OBJECTID']), point=p,
            species=a.get('SpeciesName') or '', commonName=a.get('CommonName') or '',
            treeType=a.get('TreeType') or '', sourceHeight=a.get('Height'),
            measurementDate=a.get('MeasurementDate'), positionStatus='official-public-GIS',
            dimensionsStatus='artistic-canopy-not-a-survey'))
    benches=[dict(id='uw-bench-'+str(row['attributes']['OBJECTID']),point=point(row),
        material=row['attributes'].get('Material') or 'Unknown',
        status=row['attributes'].get('FeatureStatus') or 'Unknown',
        positionStatus='official-public-GIS',dimensionsStatus='inferred',orientationStatus='path-derived-not-surveyed')
        for row in bench_rows]
    result=dict(format='uw.public-landscape/v1',geometryHash=CAMPUS['geometryHash'],
        sourceCrs='EPSG:26910',sources=[tree_source,bench_source],trees=trees,benches=benches,
        boundary='Public positions are snapshots; no claim of current existence or exact canopy, height or seating orientation. No memorial donor, dedication, notes, editor or other personal fields fetched.')
    (ROOT/'public/campus-landscape-data.js').write_text('// Generated by scripts/prepare-landscape.py. Public physical features only.\nexport const LANDSCAPE_SOURCE='+json.dumps(result,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    lock=dict(at=datetime.datetime.now(datetime.timezone.utc).isoformat(),sources=result['sources'],
        officialMap='https://gis.maps.uw.edu/portal/apps/experiencebuilder/experience/?id=3542e5a5e81d474d9ab06482d792a7ad',
        mapDiscovery='Public ExperienceBuilder item 3542e5a5e81d474d9ab06482d792a7ad identifies PublicData/MapServer/37; no login or private endpoints used for data.')
    (SOURCES/'landscape-source-lock-090.json').write_text(json.dumps(lock,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(json.dumps(dict(trees=len(trees),benches=len(benches),benchStatuses=sorted({b['status'] for b in benches}),treeTypes=sorted({t['treeType'] for t in trees}))))

if __name__=='__main__': main()
